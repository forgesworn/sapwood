/** Copy text to the clipboard, falling back to a hidden textarea when the
 * clipboard API is blocked (insecure context / permissions). Returns whether
 * the copy succeeded — callers show the value as selectable text regardless,
 * so it can always be copied by hand. */
export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text)
    return true
  } catch {
    try {
      const ta = document.createElement('textarea')
      ta.value = text
      ta.style.position = 'fixed'
      ta.style.opacity = '0'
      document.body.appendChild(ta)
      ta.select()
      const ok = document.execCommand('copy')
      document.body.removeChild(ta)
      return ok
    } catch {
      return false
    }
  }
}
